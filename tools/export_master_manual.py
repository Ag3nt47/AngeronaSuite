"""Export every manual body paragraph, table and figure for GitHub reading.

This deterministic standard-library exporter never imports Angerona. The Word
artifact remains the editorial source for its preserved edition; current source
maintenance companions are linked separately. Export validation checks exact
text-node coverage, supported structure, local figure identity and generated bytes;
Word/PDF visual QA is a separate publication requirement.
"""
from __future__ import annotations

