"""Export every manual body paragraph, table and figure for GitHub reading.

This deterministic standard-library exporter never imports Angerona. The Word
artifact remains the editorial source. Export validation checks exact text-node
coverage, supported structure, local figure identity and the generated bytes;
Word/PDF visual QA is a separate publication requirement.
"""
from __future__ import annotations

import argparse
from collections import Counter
import hashlib
from pathlib import Path, PurePosixPath
import re
import xml.etree.ElementTree as ET
from zipfile import ZipFile

ROOT = Path(__file__).resolve().parents[1]
MANUAL = ROOT / 'Angerona_Master_Manual.docx'
OUTPUT = ROOT / 'docs/master-manual.md'
W = 'http://schemas.openxmlformats.org/wordprocessingml/2006/main'
R = 'http://schemas.openxmlformats.org/officeDocument/2006/relationships'
A = 'http://schemas.openxmlformats.org/drawingml/2006/main'
NS = {'w': W, 'r': R, 'a': A}
FIGURES = {
    'security-flow-overview.png': 'Security flow from startup to evidence and recovery',
    'security-flow-startup.png': 'Safe Startup and independent recovery flow',
    'security-flow-response.png': 'Governed response and operator STOP flow',
    'security-flow-tools.png': 'Pinned toolkit preparation, separate execution and report review',
    'security-flow-breach.png': 'Native breach qualification, governed containment and managed Lift',
    'security-flow-hardening.png': 'Version 1.15 telemetry assurance, independent history and service authority layers',
}
LOCAL_PATH = re.compile(
    r'(?<![\w/])(?:(?:src|tests|tools|docs|analysis|assets)/[\w./-]+\.(?:py|ps1|md|png|json|txt|bat|toml|go)|'
    r'(?:README\.md|Angerona_Master_Manual\.(?:docx|pdf)))\b')


def escaped(text: str) -> str:
    """Retain literal text while preventing accidental Markdown formatting."""
    return re.sub(r'([\\`*_{}\[\]<>|])', r'\\\1', text).replace('\r', '')


def linked_text(text: str) -> str:
    result = []
    cursor = 0
    for match in LOCAL_PATH.finditer(text):
        relative = PurePosixPath(match.group(0))
        if '..' in relative.parts or relative.is_absolute() or not (ROOT / relative).is_file():
            continue
        result.append(escaped(text[cursor:match.start()]))
        result.append(f'[{escaped(match.group(0))}](../{relative.as_posix()})')
        cursor = match.end()
    result.append(escaped(text[cursor:]))
    return ''.join(result)


class Exporter:
    def __init__(self, archive: ZipFile):
        self.archive = archive
        self.document = ET.fromstring(archive.read('word/document.xml'))
        self.relationships = {
            rel.attrib['Id']: rel.attrib for rel in
            ET.fromstring(archive.read('word/_rels/document.xml.rels'))
        }
        self.numbering = {}
        numbering = ET.fromstring(archive.read('word/numbering.xml'))
        abstracts = {n.get(f'{{{W}}}abstractNumId'): n for n in numbering.findall('w:abstractNum', NS)}
        for num in numbering.findall('w:num', NS):
            ref = num.find('w:abstractNumId', NS)
            if ref is not None:
                self.numbering[num.get(f'{{{W}}}numId')] = abstracts.get(ref.get(f'{{{W}}}val'))
        self.seen_text = []
        self.figures = []
        self.stats = Counter()

    def inline(self, node: ET.Element) -> str:
        pieces = []
        for child in node:
            name = child.tag.rsplit('}', 1)[-1]
            if child.tag == f'{{{W}}}t':
                value = child.text or ''
                self.seen_text.append(value)
                pieces.append(linked_text(value))
            elif name == 'tab':
                pieces.append('    ')
            elif name in ('br', 'cr'):
                if child.get(f'{{{W}}}type') != 'page':
                    pieces.append('<br>')
            elif child.tag == f'{{{A}}}blip':
                relation = self.relationships.get(child.get(f'{{{R}}}embed'), {})
                target = relation.get('Target', '')
                leaf = PurePosixPath(target).name
                if leaf not in FIGURES or target != 'media/' + leaf:
                    raise ValueError(f'unrecognized manual figure: {target}')
                asset = ROOT / 'assets' / leaf
                if self.archive.read('word/' + target) != asset.read_bytes():
                    raise ValueError(f'Word figure differs from repository asset: {leaf}')
                self.figures.append(leaf)
                pieces.append(f'\n\n![{FIGURES[leaf]}](../assets/{leaf})\n\n')
            elif name == 'hyperlink':
                content = self.inline(child)
                relation = self.relationships.get(child.get(f'{{{R}}}id'), {})
                target = relation.get('Target')
                if target and re.match(r'^https?://', target):
                    pieces.append(f'[{content}]({target.replace(" ", "%20")})')
                elif target:
                    raise ValueError(f'unreviewed manual hyperlink target: {target}')
                else:
                    pieces.append(content)
            elif name in ('pPr', 'rPr', 'instrText', 'del', 'delText'):
                continue
            else:
                pieces.append(self.inline(child))
        return ''.join(pieces)

    def paragraph(self, node: ET.Element, *, cell: bool = False) -> str:
        self.stats['paragraphs'] += 1
        text = self.inline(node).strip()
        if not text:
            return ''
        style = node.find('w:pPr/w:pStyle', NS)
        label = style.get(f'{{{W}}}val', '') if style is not None else ''
        heading = re.fullmatch(r'Heading([1-6])', label, re.IGNORECASE)
        if not cell and label == 'Title':
            return '# ' + text
        if not cell and heading:
            return '#' * min(int(heading[1]) + 1, 6) + ' ' + text
        numbering = node.find('w:pPr/w:numPr', NS)
        if numbering is not None:
            number = numbering.find('w:numId', NS)
            level = numbering.find('w:ilvl', NS)
            depth = int(level.get(f'{{{W}}}val', '0')) if level is not None else 0
            abstract = self.numbering.get(number.get(f'{{{W}}}val')) if number is not None else None
            kind = None if abstract is None else abstract.find(f'w:lvl[@w:ilvl="{depth}"]/w:numFmt', NS)
            prefix = '- ' if kind is None or kind.get(f'{{{W}}}val') == 'bullet' else '1. '
            return ('' if cell else '  ' * min(depth, 8)) + prefix + text
        return text

    def table(self, node: ET.Element) -> str:
        self.stats['tables'] += 1
        rows = []
        for row in node.findall('w:tr', NS):
            cells = []
            for cell in row.findall('w:tc', NS):
                pieces = []
                for child in cell:
                    if child.tag == f'{{{W}}}p':
                        value = self.paragraph(child, cell=True)
                        if value:
                            pieces.append(value.replace('\n', '<br>'))
                    elif child.tag == f'{{{W}}}tbl':
                        raise ValueError('nested manual tables need an explicit readable export')
                    elif child.tag != f'{{{W}}}tcPr':
                        if list(child.iter(f'{{{W}}}t')):
                            raise ValueError(f'unhandled table text: {child.tag}')
                cells.append('<br><br>'.join(pieces))
                span = cell.find('w:tcPr/w:gridSpan', NS)
                count = int(span.get(f'{{{W}}}val', '1')) if span is not None else 1
                if not 1 <= count <= 32:
                    raise ValueError('unbounded manual table span')
                cells.extend([''] * (count - 1))
            rows.append(cells)
        if not rows:
            return ''
        width = max(map(len, rows))
        rows = [row + [''] * (width - len(row)) for row in rows]
        output = ['| ' + ' | '.join(row) + ' |' for row in rows]
        output.insert(1, '| ' + ' | '.join(['---'] * width) + ' |')
        return '\n'.join(output)

    def export(self) -> str:
        blocks = []
        body = self.document.find('w:body', NS)
        if body is None:
            raise ValueError('manual body is missing')
        for child in body:
            if child.tag == f'{{{W}}}p':
                value = self.paragraph(child)
            elif child.tag == f'{{{W}}}tbl':
                value = self.table(child)
            elif child.tag == f'{{{W}}}sectPr':
                continue
            else:
                raise ValueError(f'unhandled manual body structure: {child.tag}')
            if value:
                blocks.append(value)
        expected = [node.text or '' for node in body.iter(f'{{{W}}}t')]
        if self.seen_text != expected:
            raise ValueError('manual visible text coverage differs from the Word body')
        if Counter(self.figures) != Counter(FIGURES.keys()):
            raise ValueError('manual must contain exactly the three reviewed figures')
        digest = hashlib.sha256(MANUAL.read_bytes()).hexdigest()
        footer = ET.fromstring(self.archive.read('word/footer2.xml'))
        footer_text = ''.join(node.text or '' for node in footer.iter(f'{{{W}}}t'))
        revision = re.fullmatch(r'Angerona Suite  \|  v(\d+\.\d+\.\d+)  \|  (\d{1,2} [A-Za-z]+ \d{4})', footer_text)
        if revision is None:
            raise ValueError('current manual version/revision footer is ambiguous')
        introduction = (
            '<!-- Generated by tools/export_master_manual.py; do not edit by hand.\n'
            f'Word source SHA256: {digest}\n'
            f'Coverage: {len(expected)} text nodes; {self.stats["paragraphs"]} paragraphs; '
            f'{self.stats["tables"]} tables; {len(self.figures)} figures. -->\n\n'
            f'Current manual version **{revision[1]}** · Revision **{revision[2]}**\n\n'
            '[Download PDF](../Angerona_Master_Manual.pdf) · '
            '[Download Word](https://raw.githubusercontent.com/Ag3nt47/AngeronaSuite/main/Angerona_Master_Manual.docx) · '
            '[Repository guide](../README.md)\n\n'
            'This complete readable export follows the Word manual in document order. '
            'Dated validation and version-history sections retain their original scope; '
            'the final security-flow and Safe Startup chapters describe the maintained source profile.\n\n'
        )
        return introduction + '\n\n'.join(blocks).rstrip() + '\n'


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    options = parser.parse_args()
    with ZipFile(MANUAL) as archive:
        exporter = Exporter(archive)
        expected = exporter.export().encode('utf-8')
    if options.check:
        if not OUTPUT.is_file() or OUTPUT.read_bytes() != expected:
            raise SystemExit('Readable master manual is stale; run tools/export_master_manual.py')
        print('Readable manual complete text/table/figure coverage and byte identity PASS')
    else:
        OUTPUT.write_bytes(expected)
        print(f'Exported complete readable manual: {len(expected)} bytes, {dict(exporter.stats)}')


if __name__ == '__main__':
    main()
