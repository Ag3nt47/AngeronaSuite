@pytest.mark.parametrize("mutation", ["signature", "attestation", "trailing", "offset", "magic", "type", "contents", "empty-signature"])
def test_signed_or_structural_attestation_corruption_is_not_accepted(enrollment, mutation):
    e, key, *_ = enrollment
    v, c = verifier(e), candidate()
    ch = v.challenge(c)
    s = sample(e, key, ch, c)
    cert = s.certifications[0]
    if mutation == "signature":
        cert = replace(cert, signature=cert.signature[:-1] + bytes([cert.signature[-1] ^ 1]))
    elif mutation == "attestation":
        cert = replace(cert, attestation=cert.attestation[:-1] + bytes([cert.attestation[-1] ^ 1]))
    elif mutation == "trailing":
        cert = replace(cert, attestation=cert.attestation + b"x")
    elif mutation == "empty-signature":
        cert = replace(cert, signature=b"")
    else:
        kwargs = {"offset": 1} if mutation == "offset" else {"magic": 0} if mutation == "magic" else {"kind": 0x801C} if mutation == "type" else {}
        cert = attest(e, key, e.counter, ch.qualifying_data[0], b"x" if mutation == "contents" else u64(c.counter), **kwargs)
    with pytest.raises(tpm.TpmFloorError):
        v.verify(ch, replace(s, certifications=(cert, *s.certifications[1:])))


