def u16(n):
    return struct.pack(">H", n)


def u32(n):
    return struct.pack(">I", n)


def u64(n):
    return struct.pack(">Q", n)


def b2(raw):
    return u16(len(raw)) + raw


def sha(raw):
    return hashlib.sha256(raw).digest()


