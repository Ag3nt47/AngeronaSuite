class SimulatedWireTpm:
    """An explicit model transport that signs real TPMS_ATTEST byte structures."""
    def __init__(self, e, key, c):
        self.e, self.key, self.c = e, key, c
        self.calls = []
        self.rate_limit = False
        self.identity_changed = False

    def submit(self, raw):
        self.calls.append(raw)
        tag, size, code = struct.unpack(">HII", raw[:10])
        assert size == len(raw)
        if self.rate_limit:
            return u16(tpm.NO_SESSIONS) + u32(10) + u32(0x920)
        e = self.e
        if code == tpm.READ_PUBLIC:
            assert tag == tpm.NO_SESSIONS and raw[10:] == u32(e.ak_handle)
            body = e.ak.public + b2(e.ak.name) + b2(e.qualified_name if not self.identity_changed else b"changed")
        elif code == tpm.NV_READ_PUBLIC:
            assert tag == tpm.NO_SESSIONS
            nv_public = e.counter if raw[10:] == u32(e.counter.index) else e.extend
            body = nv_public.public + b2(nv_public.name)
        else:
            assert code == tpm.NV_CERTIFY and tag == tpm.SESSIONS
            sign_handle, auth_handle, nv_handle = struct.unpack(">III", raw[10:22])
            assert sign_handle == e.ak_handle and auth_handle == nv_handle
            auth_size = int.from_bytes(raw[22:26], "big")
            auth = tpm._Reader(raw[26:26 + auth_size])
            for expected in (b"fixture-AK", b"fixture-read"):
                assert auth.n(4) == tpm.PW and auth.b2() == b"" and auth.n(1) == 0 and auth.b2() == expected
            auth.end()
            params = tpm._Reader(raw[26 + auth_size:])
            nonce = params.b2()
            assert params.n(2) == e.ak.scheme and params.n(2) == tpm.SHA256
            nv_public = e.counter if nv_handle == e.counter.index else e.extend
            assert params.n(2) == nv_public.size and params.n(2) == 0
            params.end()
            contents = u64(self.c.counter) if nv_public is e.counter else self.c.expected_extend(e)
            cert = attest(e, self.key, nv_public, nonce, contents)
            parameters = b2(cert.attestation) + cert.signature
            body = u32(len(parameters)) + parameters + (b2(b"") + b"\x01" + b2(b"")) * 2
        return u16(tag) + u32(10 + len(body)) + u32(0) + body


