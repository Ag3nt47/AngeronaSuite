def test_typed_plan_binds_target_checkpoint_and_explicit_prestates(enrollment):
    e, *_ = enrollment
    args = dict(current_counter=17, current_extend=sha(b"old extend"), epoch_id=b"e" * 16, checkpoint_sha256=sha(b"rows"))
    a = tpm.prepare_anchor_plan(e, **args)
    b = tpm.prepare_anchor_plan(e, **{**args, "checkpoint_sha256": sha(b"rewritten rows")})
    later = tpm.prepare_anchor_plan(e, **{**args, "current_counter": 18})
    # Increment itself has no parameters, but its policy must bind both prestates.
    assert a.steps[0].cp_hash == later.steps[0].cp_hash
    assert a.steps[0].approved_policy != later.steps[0].approved_policy
    assert a.steps[1].approved_policy != b.steps[1].approved_policy
    assert a.steps[0].expected_counter == 17 and a.steps[1].expected_counter == 18
    assert a.steps[0].expected_extend == a.steps[1].expected_extend == args["current_extend"]
    assert a.steps[1].operand == a.candidate.extend_input(e)
    assert a.steps[0].policy_ref != a.steps[1].policy_ref
    assert a.steps[0].target_index == e.counter.index and a.steps[1].target_index == e.extend.index
    assert "no atomic CAS, command execution" in a.required_external_action


