def public(key, scheme, attrs=tpm.AK_REQUIRED):
    if scheme == tpm.ECDSA:
        n = key.public_key().public_numbers()
        body = u16(0x23) + u16(tpm.SHA256) + u32(attrs) + b2(b"")
        body += u16(tpm.NULL) + u16(scheme) + u16(tpm.SHA256) + u16(3) + u16(tpm.NULL)
        body += b2(n.x.to_bytes(32, "big")) + b2(n.y.to_bytes(32, "big"))
    else:
        n = key.public_key().public_numbers()
        body = u16(1) + u16(tpm.SHA256) + u32(attrs) + b2(b"")
        body += u16(tpm.NULL) + u16(scheme) + u16(tpm.SHA256) + u16(2048) + u32(0)
        body += b2(n.n.to_bytes(256, "big"))
    return b2(body)


def nv(index, counter, authorizer, policy_ref, *, attrs=None, size=None):
    auth_policy = tpm.policy_authorize_digest(authorizer, policy_ref)
    value = tpm.NV_BASE | (0x10 if counter else 0x40) if attrs is None else attrs
    raw = u32(index) + u16(tpm.SHA256) + u32(value) + b2(auth_policy)
    return b2(raw + u16((8 if counter else 32) if size is None else size))


def signed_document(p, issuer):
    canonical = json.dumps(p, sort_keys=True, separators=(",", ":"), ensure_ascii=True).encode("ascii")
    signature = issuer.sign(b"Angerona-TPM-NV-enrollment-v1\x00" + canonical)
    return json.dumps({"payload": p, "signature": signature.hex()}).encode("ascii")


