class SimulatedTbsApi:
    def __init__(self):
        self.created, self.submitted, self.closed = [], [], []
        self.started = threading.Event()
        self.finish = threading.Event()
        self.delay = False
        self.fail_create = False
        self.fail_close = False

    def create_context(self):
        owner = object()
        self.created.append(owner)
        if self.fail_create:
            raise RuntimeError("simulated ambiguous context creation")
        return owner

    def submit(self, context, command):
        self.submitted.append((context, command))
        self.started.set()
        if self.delay:
            assert self.finish.wait(3)
        return u16(tpm.NO_SESSIONS) + u32(10) + u32(0)

    def close(self, context):
        self.closed.append(context)
        if self.fail_close:
            raise RuntimeError("simulated ambiguous native close")


def read_command():
    return u16(tpm.NO_SESSIONS) + u32(14) + u32(tpm.READ_PUBLIC) + u32(0x81010020)


def test_source_or_revoked_installed_authority_dispatches_no_tbs_call():
    api = SimulatedTbsApi()
    with pytest.raises(tpm.TpmFloorError) as error:
        tpm.WindowsTbsReadonlyTransport(lambda: False, _api=api)
    assert error.value.code == "installed-authority" and not api.created
    allowed = [True]
    transport = tpm.WindowsTbsReadonlyTransport(lambda: allowed[0], _api=api)
    allowed[0] = False
    with pytest.raises(tpm.TpmFloorError):
        transport.submit(read_command())
    assert not api.submitted
    assert transport.close() and transport.cleanup_proven


