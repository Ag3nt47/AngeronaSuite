@pytest.mark.parametrize("mutation", ["wrong-size", "trailing", "wrong-tag", "truncated", "auth-nonce", "auth-attrs", "auth-hmac", "parameter-size", "error-with-body"])
def test_strict_native_response_framing_rejects_malformed_buffers(mutation):
    parameters = b"fixture parameters"
    auth = (b2(b"") + b"\x01" + b2(b"")) * 2
    body = u32(len(parameters)) + parameters + auth
    raw = u16(tpm.SESSIONS) + u32(10 + len(body)) + u32(0) + body
    if mutation == "wrong-size":
        raw = raw[:2] + u32(len(raw) + 1) + raw[6:]
    elif mutation == "trailing":
        raw += b"x"
    elif mutation == "wrong-tag":
        raw = u16(tpm.NO_SESSIONS) + raw[2:]
    elif mutation == "truncated":
        raw = raw[:8]
    elif mutation == "parameter-size":
        raw = raw[:10] + u32(8000) + raw[14:]
    elif mutation == "error-with-body":
        raw = raw[:6] + u32(0x920) + raw[10:]
    else:
        bad_auth = b2(b"nonce") + b"\x01" + b2(b"") if mutation == "auth-nonce" else b2(b"") + b"\x00" + b2(b"") if mutation == "auth-attrs" else b2(b"") + b"\x01" + b2(b"hmac")
        body = u32(len(parameters)) + parameters + bad_auth + auth[5:]
        raw = u16(tpm.SESSIONS) + u32(10 + len(body)) + u32(0) + body
    with pytest.raises(tpm.TpmFloorError) as error:
        tpm._response(raw, sessions=True)
    assert error.value.code == "wire"


