def candidate(counter=18, *, digest=None):
    return tpm.CheckpointCandidate(counter, sha(b"previous hardware extend state"), b"e" * 16,
                                   digest or sha(b"exact stored rows with HMAC representations"))


def verifier(e, clock=None):
    return tpm.TpmFloorVerifier(e, clock=(lambda: 200.0) if clock is None else lambda: clock[0], wall_clock=lambda: 1000)


def attest(e, key, nv_public, nonce, contents, *, safe=1, offset=0, magic=0xFF544347, kind=0x8014):
    raw = u32(magic) + u16(kind) + b2(e.qualified_name) + b2(nonce)
    raw += u64(1234567) + u32(3) + u32(8) + bytes([safe]) + u64(17)
    raw += b2(nv_public.name) + u16(offset) + b2(contents)
    if e.ak.scheme == tpm.ECDSA:
        signature = key.sign(raw, ec.ECDSA(hashes.SHA256()))
        a, b = decode_dss_signature(signature)
        signature = u16(tpm.ECDSA) + u16(tpm.SHA256) + b2(a.to_bytes(32, "big")) + b2(b.to_bytes(32, "big"))
    else:
        pad = padding.PKCS1v15() if e.ak.scheme == tpm.RSASSA else padding.PSS(mgf=padding.MGF1(hashes.SHA256()), salt_length=32)
        signature = u16(e.ak.scheme) + u16(tpm.SHA256) + b2(key.sign(raw, pad, hashes.SHA256()))
    return tpm.Certification(raw, signature)


def sample(e, key, challenge, c, *, before=None, after=None, extend=None, safe=1):
    before = c.counter if before is None else before
    after = before if after is None else after
    extend = c.expected_extend(e) if extend is None else extend
    certs = tuple(attest(e, key, nv_public, nonce, data, safe=safe) for nv_public, nonce, data in zip(
        (e.counter, e.extend, e.counter), challenge.qualifying_data, (u64(before), extend, u64(after)), strict=True))
    return tpm.FloorSample(e.ak.public, e.ak.name, e.qualified_name, e.counter.public, e.counter.name,
                           e.extend.public, e.extend.name, certs)


